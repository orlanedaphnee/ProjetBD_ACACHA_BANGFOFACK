SET FOREIGN_KEY_CHECKS = 0;
DROP DATABASE IF EXISTS streamingdb;
CREATE DATABASE streamingdb;
USE streamingdb;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE Formule (
    id_formule INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nom_formule VARCHAR(100) UNIQUE NOT NULL,
    prix_mensuel DECIMAL(15, 2) NOT NULL,
    nb_ecran_max INT UNSIGNED NOT NULL,
    qualite_max VARCHAR(50) NOT NULL
);

CREATE TABLE Compte (
    id_compte INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    email VARCHAR(255) UNIQUE NOT NULL,
    mot_de_passe VARCHAR(255) NOT NULL,
    date_creation DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Souscrire (
    id_compte INT UNSIGNED NOT NULL,
    id_formule INT UNSIGNED NOT NULL,
    date_debut DATE NOT NULL,
    date_fin DATE DEFAULT NULL,
    etat VARCHAR(15) NOT NULL,
    PRIMARY KEY (id_compte, id_formule, date_debut),
    CONSTRAINT FK_SOUSCRIRE_COMPTE FOREIGN KEY (id_compte) REFERENCES Compte (id_compte) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_SOUSCRIRE_FORMULE FOREIGN KEY (id_formule) REFERENCES Formule (id_formule) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Profil (
    id_profil INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nom_profil VARCHAR(100) NOT NULL,
    type_profil VARCHAR(50) NOT NULL,
    langue_preferee VARCHAR(50) NOT NULL,
    categorie_age_max VARCHAR(20) NOT NULL,
    id_compte INT UNSIGNED NOT NULL,
    CONSTRAINT FK_PROFIL_COMPTE FOREIGN KEY (id_compte) REFERENCES Compte (id_compte) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Genre (
    nom_genre VARCHAR(100) PRIMARY KEY,
    nom_genre_parent VARCHAR(100) DEFAULT NULL,
    CONSTRAINT FK_GENRE_PARENT FOREIGN KEY (nom_genre_parent) REFERENCES Genre (nom_genre) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE Contenu (
    id_contenu INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    type_contenu VARCHAR(50) NOT NULL,
    titre VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    date_sortie DATE NOT NULL,
    duree_film INT UNSIGNED DEFAULT NULL
);

CREATE TABLE Classer (
    id_contenu INT UNSIGNED NOT NULL,
    nom_genre VARCHAR(100) NOT NULL,
    PRIMARY KEY (id_contenu, nom_genre),
    CONSTRAINT FK_CLASSER_CONTENU FOREIGN KEY (id_contenu) REFERENCES Contenu (id_contenu) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_CLASSER_GENRE FOREIGN KEY (nom_genre) REFERENCES Genre (nom_genre) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Acteur (
    id_acteur INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nom_acteur VARCHAR(150) NOT NULL
);

CREATE TABLE Personnage (
    id_personnage INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nom_personnage VARCHAR(150) NOT NULL
);

CREATE TABLE Incarner (
    id_contenu INT UNSIGNED NOT NULL,
    id_acteur INT UNSIGNED NOT NULL,
    id_personnage INT UNSIGNED NOT NULL,
    PRIMARY KEY (id_contenu, id_acteur, id_personnage),
    CONSTRAINT FK_INCARNER_CONTENU FOREIGN KEY (id_contenu) REFERENCES Contenu (id_contenu) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_INCARNER_ACTEUR FOREIGN KEY (id_acteur) REFERENCES Acteur (id_acteur) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_INCARNER_PERSONNAGE FOREIGN KEY (id_personnage) REFERENCES Personnage (id_personnage) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Visionnage (
    id_profil INT UNSIGNED NOT NULL,
    date_heure_debut DATETIME NOT NULL,
    duree_regardee INT UNSIGNED NOT NULL,
    type_appareil VARCHAR(50) NOT NULL,
    id_contenu INT UNSIGNED NOT NULL,
    PRIMARY KEY (id_profil, date_heure_debut),
    CONSTRAINT FK_VISIONNAGE_PROFIL FOREIGN KEY (id_profil) REFERENCES Profil (id_profil) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_VISIONNAGE_CONTENU FOREIGN KEY (id_contenu) REFERENCES Contenu (id_contenu) ON DELETE CASCADE ON UPDATE CASCADE
);